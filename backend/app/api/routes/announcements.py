# Announcements Routes
# This module will define endpoints for school-wide announcements.
# Planned endpoints:
#   GET    /announcements        → list all active announcements (filterable by audience role)
#   POST   /announcements        → create a new announcement (admin/teacher)
#   GET    /announcements/{id}   → get a specific announcement
#   PUT    /announcements/{id}   → edit an announcement
#   DELETE /announcements/{id}   → delete/archive an announcement
