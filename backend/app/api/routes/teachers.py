# Teachers Routes
# This module will define CRUD endpoints for teacher management.
# Planned endpoints:
#   GET    /teachers           → list all teachers (admin access)
#   POST   /teachers           → add a new teacher (admin only)
#   GET    /teachers/{id}      → get a teacher's profile
#   PUT    /teachers/{id}      → update teacher information
#   DELETE /teachers/{id}      → remove a teacher record
#   GET    /teachers/{id}/classes  → list all classes assigned to a teacher
