# Students Routes
# This module will define CRUD endpoints for student management.
# Planned endpoints:
#   GET    /students           → list all students (admin/teacher access)
#   POST   /students           → enroll a new student (admin only)
#   GET    /students/{id}      → get a student's full profile
#   PUT    /students/{id}      → update student information
#   DELETE /students/{id}      → remove a student record
#   GET    /students/{id}/grades      → get all grades for a student
#   GET    /students/{id}/attendance  → get attendance history for a student
